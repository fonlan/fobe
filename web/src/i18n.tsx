export type Locale = 'zh-CN' | 'en-US';

const LOCALE_KEY = 'fobe.lang';
const dicts: Record<Locale, Record<DictKey, string>> = { 'zh-CN': zh, 'en-US': en };

function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem(LOCALE_KEY);
    if (saved === 'zh-CN' || saved === 'en-US') return saved;
  } catch {
    // storage unavailable
  }
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh')
    ? 'zh-CN'
    : 'en-US';
}

export type TFn = (key: string, vars?: Record<string, string | number>) => string;

interface I18nCtx {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: TFn;
}

const Ctx = createContext<I18nCtx | null>(null);

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detectLocale);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem(LOCALE_KEY, l);
    } catch {
      // storage unavailable
    }
    document.documentElement.lang = l;
  }, []);

  const t = useCallback<TFn>(
    (key, vars) => {
      const raw = dicts[locale][key as DictKey] ?? dicts['en-US'][key as DictKey] ?? key;
      return interpolate(raw, vars);
    },
    [locale],
  );

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}

/** Translate a dynamic alert/command kind; falls back to the raw kind. */
export function kindText(t: TFn, kind: string): string {
  const key = 'kind_' + kind;
  return t(key) === key ? kind : t(key);
}
